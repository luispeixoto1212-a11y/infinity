/** Nome português da constelação a partir da abreviatura da IAU (por exemplo, "Ori" → "Orion"). */
export function constellationName(abbr?: string | null): string {
  if (!abbr) return '—';
  return CONSTELLATION_NAMES_PT[abbr] ?? CONSTELLATIONS[abbr]?.name ?? abbr;
}

/** Nome oficial latino da IAU. */
export function constellationLatin(abbr?: string | null): string | undefined {
  return abbr ? CONSTELLATIONS[abbr]?.name : undefined;
}
