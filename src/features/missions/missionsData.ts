export function findMission(id: string): Mission | undefined {
  return MISSIONS.find((m) => m.id === id);
}

/** Ano decimal de uma data AAAA, AAAA-MM ou AAAA-MM-DD (para a linha temporal). */
export function decimalYear(date: string): number {
  const [y, m, d] = date.split('-').map(Number) as [number, number | undefined, number | undefined];
  return y + ((m ?? 7) - 1) / 12 + ((d ?? 15) - 1) / 365.25;
}

const MONTHS = ['janeiro', 'fevereiro', 'março', 'abril', 'maio', 'junho', 'julho', 'agosto', 'setembro', 'outubro', 'novembro', 'dezembro'];

/** "16 de julho de 1969", "julho de 2027" ou "2028", conforme a precisão da data. */
export function formatMissionDate(date: string): string {
  const [y, m, d] = date.split('-').map(Number) as [number, number | undefined, number | undefined];
  if (!m) return String(y);
  if (!d) return `${MONTHS[m - 1]} de ${y}`;
  return `${d} de ${MONTHS[m - 1]} de ${y}`;
}
