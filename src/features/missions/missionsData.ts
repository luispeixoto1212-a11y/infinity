/**
 * Missões espaciais: históricas, em curso e planeadas.
 *
 * Datas: AAAA-MM-DD (UTC) ou AAAA-MM quando só o mês é conhecido. Para as missões em curso e futuras, o estado
 * foi verificado a 14/10/2026 na fonte indicada em statusSource; datas futuras são planos das agências e podem mudar.
 * As datas históricas seguem o NASA Space Science Data Coordinated Archive (NSSDCA) e as páginas das agências.
 */

export type MissionCategory = 'earth' | 'crewed' | 'planetary' | 'small-bodies' | 'telescope' | 'sun' | 'moon';
export type MissionStatus = 'completed' | 'active' | 'cruise' | 'planned' | 'unconfirmed';

export interface MissionSource {
  title: string;
  publisher: string;
  url: string;
}

export interface MissionEvent {
  date: string;
  text: string;
  /** Acontecimento ainda não ocorrido (plano da agência). */
  planned?: boolean;
}

export interface Mission {
  id: string;
  name: string;
  /** Outros nomes para a pesquisa. */
  aliases: string[];
  agencies: string[];
  category: MissionCategory;
  status: MissionStatus;
  /** Frase sobre o estado atual, com data. */
  statusText: string;
  statusSource?: MissionSource;
  launch: string;
  /** Fim da missão (missões concluídas). */
  end?: string;
  /** Fim planeado ou chegada ao destino, para o desenho da linha temporal. */
  plannedUntil?: string;
  vehicle?: string;
  destination: string;
  /** Fichas da aplicação relacionadas (slugs). */
  bodies: string[];
  summary: string;
  objectives: string[];
  instruments: Array<[string, string]>;
  discoveries: string[];
  events: MissionEvent[];
  sources: MissionSource[];
  /** Pesquisa na NASA Image and Video Library (só missões com imagens da NASA). */
  imageQuery?: { q: string; mustInclude: string[] };
}

export const MISSIONS_CHECKED = '2026-10-14';

const nssdca = (id: string, name: string): MissionSource => ({
  title: `${name} — NSSDCA Master Catalog`,
  publisher: 'NASA Space Science Data Coordinated Archive',
  url: `https://nssdc.gsfc.nasa.gov/nmc/spacecraft/display.action?id=${id}`,
});
const nasaMission = (slug: string, name: string): MissionSource => ({
  title: name,
  publisher: 'NASA Science',
  url: `https://science.nasa.gov/mission/${slug}/`,
});
const esaScience = (path: string, name: string): MissionSource => ({
  title: name,
  publisher: 'ESA',
  url: `https://www.esa.int/Science_Exploration/Space_Science/${path}`,
});

